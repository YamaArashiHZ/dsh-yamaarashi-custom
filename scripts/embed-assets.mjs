/**
 * Generate `src/client/generated/assets.ts` from the checked-in base64 asset.
 *
 * The browser bundle may not import images (the DSH client factory only has
 * the platform module table and package-local chunks), so the default mascot
 * ships as a data URL inside a generated TS module.
 *
 * Run through `npm run assets`; `build` and `typecheck` both depend on it.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(root, 'assets/mascot-512.webp.b64')
const outDir = resolve(root, 'src/client/generated')
const outFile = resolve(outDir, 'assets.ts')

const base64 = readFileSync(source, 'utf8').trim()
if (base64.length === 0) throw new Error(`[embed-assets] ${source} is empty`)

mkdirSync(outDir, { recursive: true })
writeFileSync(outFile, [
  '// Generated by scripts/embed-assets.mjs from assets/mascot-512.webp.b64 — do not edit.',
  '// The browser bundle cannot import images, so the default mascot ships as a data URL.',
  // Explicit `: string` keeps the declaration file small (a literal type would
  // copy the whole base64 into lib/types).
  `export const MASCOT_WEBP_DATA_URL: string = 'data:image/webp;base64,${base64}'`,
  '',
].join('\n'))

console.log(`[embed-assets] wrote ${outFile} (${base64.length} base64 chars)`)
